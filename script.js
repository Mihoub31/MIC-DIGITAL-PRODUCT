const storageKey = 'mic-lang';
const langButtons = [...document.querySelectorAll('.lang-btn')];
const defaultLang = 'en';

function setLanguage(lang) {
  const selected = translations[lang] ? lang : defaultLang;
  document.documentElement.lang = selected;
  document.body.classList.toggle('rtl', selected === 'ar');

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    if (translations[selected][key]) {
      element.textContent = translations[selected][key];
    }
  });

  langButtons.forEach((button) => {
    const active = button.dataset.lang === selected;
    button.classList.toggle('active', active);
    button.setAttribute('aria-pressed', String(active));
  });

  localStorage.setItem(storageKey, selected);
}

langButtons.forEach((button) => {
  button.addEventListener('click', () => setLanguage(button.dataset.lang));
});

const saved = localStorage.getItem(storageKey) || defaultLang;
setLanguage(saved);

